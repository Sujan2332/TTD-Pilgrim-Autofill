// page-bridge.js and how content.js uses it, on saved TTD pages.
const { read, referencePage, loadPage, stopPage, mockDropdown, sleep, test, run, assert } = require("./helpers");

const CALENDAR_PAGE = referencePage("calendar/Calendar_Ammavari_Page.html");
const TEMPLE_PAGE = referencePage("arjitha-seva/temples/temple_1_Srivari_Temple_-_Tirumala.html");
const PADMAVATHI = "Sri Padmavathi Ammavari Temple - Tiruchanoor";
const TEMPLES = ["Srivari Temple - Tirumala", "Sri Govindarajaswamy Temple - Tirupathi", PADMAVATHI, "Srinivasa Temple - Tiruchanoor"];

// content.js line 37 carries an inline copy of page-bridge.js (fallback injector) that must be regenerated by hand
test("inline bridge copy in content.js matches page-bridge.js", () => {
  const line = read("content.js").split(/\r?\n/).find((l) => /^\s*script\.textContent = "/.test(l));
  assert(line, "inline copy line (script.textContent = \"...\") not found in content.js");
  const inline = JSON.parse(line.match(/script\.textContent = (".*");\s*$/)[1]).replace(/\r\n/g, "\n");
  const file = read("page-bridge.js").replace(/\r\n/g, "\n");
  assert(inline === file, "content.js's inline copy is OUT OF DATE - regenerate it from page-bridge.js (JSON.stringify of the file)");
});

// Each running bridge wraps fetch once and adds 1 to <html data-ttd-pending> per request
function bridgeInstances(w) {
  const before = Number(w.document.documentElement.getAttribute("data-ttd-pending") || 0);
  w.fetch("https://example.invalid/");
  return Number(w.document.documentElement.getAttribute("data-ttd-pending")) - before;
}

// Calendar page with TTD's ticket dropdown (toggling) and click counters on TTD's real Back / Continue
function calendarPage(bridge) {
  let stats;
  const { window: w } = loadPage(CALENDAR_PAGE, {
    url: "https://ttdevasthanams.ap.gov.in/sed/slot-booking",
    bridge,
    beforeScripts(w) {
      const input = w.document.querySelector('[class*="slotHeader"] input.floating-input');
      stats = mockDropdown(w, input, ["1", "2", "3", "4", "5", "6"], input.parentElement.querySelector('[style*="z-index: 999"]'));
      stats.input = input;
      const [back, cont] = w.document.querySelectorAll('[class*="greyButtonContainer"] button');
      stats.back = 0;
      stats.cont = 0;
      back.addEventListener("click", () => stats.back++);
      cont.addEventListener("click", () => stats.cont++);
      cont.__reactProps$mock = { onClick: () => stats.cont++ };
    },
  });
  return { w, stats };
}

for (const [label, bridge] of [["normal page load", true], ["bridge not running yet (inline fallback)", false]]) {
  test(`${label}: exactly one bridge runs, even after repeated ensurePageBridge()`, async () => {
    const { w } = calendarPage(bridge);
    await sleep(50);
    for (let i = 0; i < 6; i++) w.ensurePageBridge();
    assert(bridgeInstances(w) === 1, `${bridgeInstances(w)} bridges running`);
    assert(w.document.querySelectorAll("#__ttd_page_bridge_tag").length <= 1, "bridge tag added more than once");
    stopPage(w);
  });

  test(`${label}: tickets set to 4 with a single dropdown open`, async () => {
    const { w, stats } = calendarPage(bridge);
    const ok = await w.selectTicketCount(4);
    stopPage(w);
    assert(ok === true && stats.input.value === "4", `ticket count is "${stats.input.value}"`);
    assert(stats.toggles === 1, `dropdown toggled ${stats.toggles} times (must open once - it toggles on every click)`);
  });

  test(`${label}: calendar Continue clicked exactly once, Back never`, async () => {
    const { w, stats } = calendarPage(bridge);
    w.dispatchEvent(new w.CustomEvent("__TTD_CLICK_CONTINUE__"));
    w.dispatchEvent(new w.CustomEvent("__TTD_CLICK_CONTINUE__")); // a duplicate request must be ignored
    await sleep(600);
    stopPage(w);
    assert(stats.cont === 1, `Continue clicked ${stats.cont} times`);
    assert(stats.back === 0, `Back clicked ${stats.back} times (sends the user home)`);
  });

  test(`${label}: Arjitha temple "${PADMAVATHI}" selected quickly`, async () => {
    let input;
    const { window: w } = loadPage(TEMPLE_PAGE, {
      url: "https://ttdevasthanams.ap.gov.in/arjitha-seva",
      bridge,
      beforeScripts(w) {
        input = w.document.querySelector('input[name="templeSelected"], input[placeholder*="Select Temple"], input[label="Temple"]');
        mockDropdown(w, input, TEMPLES);
      },
    });
    const start = Date.now();
    const ok = await w.selectTempleOnPage(PADMAVATHI);
    const ms = Date.now() - start;
    stopPage(w);
    assert(ok && input.value === PADMAVATHI, `temple is "${input.value}"`);
    assert(ms < 1000, `took ${ms} ms (a lost bridge request waits out a 2.5 s timeout)`);
  });
}

run();
